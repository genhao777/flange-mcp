def _make_render(
    shape: Any,
    path: Path,
    measured: dict[str, Any],
    context: dict[str, Any] | None = None,
) -> None:
    """Create a presentation preview from the delivered B-rep tessellation.

    This is intentionally separate from the technical drawing.  It adds a
    restrained steel-like finish for a demo cover image while every surface
    still comes from the actual solid rather than from the parameter table.
    """
    from PIL import Image, ImageDraw, ImageFilter, ImageFont

    width, height = 1600, 1000
    image = Image.new("RGB", (width, height), "#0b1726")
    background = ImageDraw.Draw(image)
    top = (11, 23, 38)
    bottom = (30, 66, 88)
    for y in range(height):
        ratio = y / max(height - 1, 1)
        color = tuple(int(top[i] * (1 - ratio) + bottom[i] * ratio) for i in range(3))
        background.line((0, y, width, y), fill=color)

    vertices, triangles = shape.tessellate(0.45, angular_tolerance=0.12)
    angle = radians(30)
    ca, sa = cos(angle), sin(angle)

    def project(vertex: Any) -> tuple[float, float, float]:
        x, y, z = float(vertex.X), float(vertex.Y), float(vertex.Z)
        # Camera looks from the front-right and slightly above the part.
        sx = (x - y) * ca
        sy = -(z * 1.35 + (x + y) * sa)
        # The depth axis is orthogonal to the screen basis above.  Keeping it
        # consistent with the projection prevents back faces from appearing
        # through the top face when triangles are painter-sorted.
        depth = -(x + y) * sa + z * 0.88
        return sx, sy, depth

    projected = [project(vertex) for vertex in vertices]
    min_x = min(point[0] for point in projected)
    max_x = max(point[0] for point in projected)
    min_y = min(point[1] for point in projected)
    max_y = max(point[1] for point in projected)
    span = max(max_x - min_x, max_y - min_y, 1.0)
    scale = min(980 / span, 7.0)
    center_x = (min_x + max_x) / 2
    center_y = (min_y + max_y) / 2

    def screen(point: tuple[float, float, float]) -> tuple[int, int]:
        return (
            int(width * 0.52 + (point[0] - center_x) * scale),
            int(height * 0.56 + (point[1] - center_y) * scale),
        )

    # A soft ground shadow gives the preview a product-like presentation.
    shadow = Image.new("RGBA", (width, height), (0, 0, 0, 0))
    shadow_draw = ImageDraw.Draw(shadow)
    shadow_draw.ellipse((350, 715, 1200, 865), fill=(0, 0, 0, 130))
    shadow = shadow.filter(ImageFilter.GaussianBlur(28))
    image = Image.alpha_composite(image.convert("RGBA"), shadow)
    draw = ImageDraw.Draw(image)

    light = (0.45, -0.35, 0.82)
    light_length = sqrt(sum(value * value for value in light))
    light = tuple(value / light_length for value in light)

    def triangle_color(p0: Any, p1: Any, p2: Any) -> tuple[int, int, int, int]:
        ax, ay, az = float(p1.X - p0.X), float(p1.Y - p0.Y), float(p1.Z - p0.Z)
        bx, by, bz = float(p2.X - p0.X), float(p2.Y - p0.Y), float(p2.Z - p0.Z)
        nx, ny, nz = ay * bz - az * by, az * bx - ax * bz, ax * by - ay * bx
        length = sqrt(nx * nx + ny * ny + nz * nz) or 1.0
        nx, ny, nz = nx / length, ny / length, nz / length
        intensity = max(0.0, nx * light[0] + ny * light[1] + nz * light[2])
        if nz > 0.55:
            base = (112, 157, 181)
        elif abs(nz) < 0.35:
            base = (64, 96, 119)
        else:
            base = (82, 120, 143)
        factor = 0.62 + 0.55 * intensity
        return tuple(min(255, int(channel * factor)) for channel in base) + (255,)

    # Painter's algorithm: far triangles first, near triangles last.
    ordered = sorted(
        triangles,
        key=lambda triangle: sum(projected[index][2] for index in triangle) / 3,
    )
    for i0, i1, i2 in ordered:
        polygon = [screen(projected[index]) for index in (i0, i1, i2)]
        draw.polygon(polygon, fill=triangle_color(vertices[i0], vertices[i1], vertices[i2]))

    font = ImageFont.load_default()
    title_font = (
        ImageFont.truetype("arial.ttf", 34)
        if Path("C:/Windows/Fonts/arial.ttf").exists()
        else font
    )
    draw.text((70, 55), "OILFIELD FLANGE / 3D PREVIEW", fill=(235, 245, 250), font=title_font)
    draw.text(
        (72, 105),
        "STEP B-rep tessellation · presentation view",
        fill=(167, 202, 218),
        font=font,
    )
    caption = _context_caption(context)
    if caption:
        draw.text((72, 128), caption, fill=(145, 184, 202), font=font)
    draw.rounded_rectangle((70, 835, 700, 925), radius=16, fill=(7, 18, 30, 190), outline=(77, 130, 154, 180), width=2)
    draw.text(
        (94, 858),
        (
            f"OD {measured['od']:g} mm   T {measured['thickness']:g} mm   "
            f"{measured['bolt_count']} × Φ{measured['bolt_diameter']:g}   "
            f"PCD {measured['pcd']:g} mm"
        ),
        fill=(232, 242, 246),
        font=font,
    )
    draw.text((94, 892), "PARAMETRIC SOLID · HUMAN REVIEW REQUIRED", fill=(173, 205, 218), font=font)
    image.convert("RGB").save(path, quality=95)


