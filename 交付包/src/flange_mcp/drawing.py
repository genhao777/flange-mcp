def _make_dxf(shape: Any, path: Path, measured: dict[str, Any]) -> dict[str, Any]:
    from build123d import ExportDXF, LineType, Pos, Unit
    import ezdxf

    views = {view.name: view for view in _make_views(shape)}
    offsets = {
        "front": (0.0, 0.0),
        "top": (0.0, -(float(measured["od"]) + 80.0)),
        "left": (float(measured["od"]) + 80.0, 0.0),
    }
    exporter = ExportDXF(unit=Unit.MM)
    exporter.add_layer("HIDDEN", line_type=LineType.DASHED)
    exporter.add_layer("VISIBLE")
    for name, view in views.items():
        dx, dy = offsets[name]
        # Hidden lines first, visible lines second so visible geometry wins.
        exporter.add_shape(Pos(dx, dy, 0) * view.hidden, layer="HIDDEN")
        exporter.add_shape(Pos(dx, dy, 0) * view.visible, layer="VISIBLE")

    doc = exporter._document
    dimstyle = doc.dimstyles.new("GB") if "GB" not in doc.dimstyles else doc.dimstyles.get("GB")
    dimstyle.dxf.dimlfac = 1.0
    dimstyle.dxf.dimtxt = 3.0
    dimstyle.dxf.dimasz = 2.5
    msp = exporter._modelspace
    top_x, top_y = offsets["top"]
    od = float(measured["od"])
    center_hole = float(measured["center_hole"])
    pcd = float(measured["pcd"])
    bolt_diameter = float(measured["bolt_diameter"])
    thickness = float(measured["thickness"])
    r = od / 2
    bolt_r = pcd / 2
    dimensions = [
        msp.add_linear_dim(
            base=(top_x, top_y - r - 15),
            p1=(top_x - r, top_y),
            p2=(top_x + r, top_y),
            location=(top_x, top_y - r - 15),
            text="<>",
            dimstyle="GB",
        ),
        msp.add_diameter_dim(
            center=(top_x, top_y),
            radius=center_hole / 2,
            location=(top_x + center_hole / 2 + 18, top_y),
            dimstyle="GB",
        ),
        msp.add_linear_dim(
            base=(top_x, top_y - bolt_r - 10),
            p1=(top_x - bolt_r, top_y),
            p2=(top_x + bolt_r, top_y),
            location=(top_x, top_y - bolt_r - 10),
            text="<>",
            dimstyle="GB",
        ),
        msp.add_diameter_dim(
            center=(top_x + bolt_r, top_y),
            radius=bolt_diameter / 2,
            location=(top_x + bolt_r + 15, top_y + 10),
            dimstyle="GB",
        ),
        msp.add_linear_dim(
            base=(r + 20, 0),
            p1=(r, 0),
            p2=(r, -thickness),
            location=(r + 20, -thickness / 2),
            text="<>",
            angle=90,
            dimstyle="GB",
        ),
    ]
    for dimension in dimensions:
        dimension.render()

    exporter.write(path)
    check = ezdxf.readfile(path)
    return {
        "dimension_count": len(check.modelspace().query("DIMENSION")),
        "view_count": len(views),
        "readback_dimensions": {
            "od": od,
            "center_hole": center_hole,
            "pcd": pcd,
            "bolt_diameter": bolt_diameter,
            "thickness": thickness,
        },
        "projection_source": "delivered STEP B-rep via build123d.Drawing",
    }


def make_drawing(
    shape: Any,
    spec: FlangeSpec,
    output_dir: str | Path,
    formats: Iterable[str] = ("dxf", "pdf", "png"),
    context: dict[str, Any] | None = None,
    assembly: FlangedSpoolSpec | None = None,
) -> dict[str, Any]:
    validate_spec(spec)
    output = Path(output_dir)
    output.mkdir(parents=True, exist_ok=True)
    requested = {item.lower() for item in formats}
    measured = _measure_shape(shape)
    paths: dict[str, str] = {}
    readback: dict[str, Any] = {}
    assembly_metadata: dict[str, Any] | None = None

    if "png" in requested:
        png_path = output / "flange.png"
        _make_png(shape, png_path, measured, context)
        paths["png"] = str(png_path)
    if "render" in requested:
        render_path = output / "flange_render.png"
        _make_render(shape, render_path, measured, context)
        paths["render"] = str(render_path)
    if "viewer" in requested:
        viewer_path = output / "flange_viewer.html"
        _make_viewer(shape, viewer_path, measured, context)
        paths["viewer"] = str(viewer_path)
    if "pdf" in requested:
        pdf_path = output / "flange.pdf"
        _make_pdf(shape, pdf_path, measured, context)
        paths["pdf"] = str(pdf_path)
    if "dxf" in requested:
        dxf_path = output / "flange.dxf"
        readback = _make_dxf(shape, dxf_path, measured)
        paths["dxf"] = str(dxf_path)
    if "assembly" in requested:
        assembly = assembly or FlangedSpoolSpec.from_mapping({}, spec)
        assembly_shape, assembly_metadata = make_flanged_spool(shape, spec, assembly)
        component_shapes = flanged_spool_component_shapes(shape, spec, assembly)
        from build123d import export_step, export_stl

        assembly_step = output / "flange_spool.step"
        assembly_stl = output / "flange_spool.stl"
        export_step(assembly_shape, str(assembly_step))
        export_stl(assembly_shape, str(assembly_stl))
        assembly_viewer = output / "flange_spool_viewer.html"
        _make_viewer(
            assembly_shape,
            assembly_viewer,
            measured,
            context,
            assembly=assembly_metadata,
            view_title="法兰短节 / 装配三维视图",
            view_subtitle="装配组件 · 水平绕 Y 轴 · 垂直绕 X 轴 · 滚轮缩放",
            file_stem="flange_spool",
            component_shapes=component_shapes,
        )
        assembly_report = output / "assembly.json"
        assembly_report.write_text(
            json.dumps(assembly_metadata, ensure_ascii=False, indent=2),
            encoding="utf-8",
        )
        paths["assembly_step"] = str(assembly_step)
        paths["assembly_stl"] = str(assembly_stl)
        paths["assembly_viewer"] = str(assembly_viewer)
        paths["assembly_report"] = str(assembly_report)

    result = {
        "ok": True,
        "formats": sorted(requested),
        "paths": paths,
        "requested_spec": spec.as_dict(),
        "context": context or {},
        "measured_dimensions": measured,
        "projection_source": "delivered STEP B-rep via build123d.Drawing",
        "render_source": (
            "delivered STEP B-rep tessellation"
            if "render" in requested
            else None
        ),
        "viewer_source": (
            "delivered STEP B-rep tessellation with offline canvas controls"
            if "viewer" in requested
            else None
        ),
        "assembly_source": (
            "parametric flange-pipe-flange composite from delivered STEP B-rep"
            if "assembly" in requested
            else None
        ),
        "assembly": assembly_metadata,
        "readback": readback,
    }
    (output / "drawing.json").write_text(
        json.dumps(result, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    return result
