_PDF_FONT_NAME = "Helvetica"


def _register_pdf_font() -> str:
    """Register a Chinese engineering font when the host provides one."""
    global _PDF_FONT_NAME
    try:
        from reportlab.pdfbase import pdfmetrics
        from reportlab.pdfbase.ttfonts import TTFont

        if "FangSong" in pdfmetrics.getRegisteredFontNames():
            _PDF_FONT_NAME = "FangSong"
            return _PDF_FONT_NAME
        candidates = (
            Path("C:/Windows/Fonts/simfang.ttf"),
            Path("/usr/share/fonts/truetype/arphic/uming.ttc"),
        )
        for candidate in candidates:
            if candidate.exists():
                try:
                    pdfmetrics.registerFont(TTFont("FangSong", str(candidate)))
                    _PDF_FONT_NAME = "FangSong"
                    return _PDF_FONT_NAME
                except Exception:
                    continue
    except Exception:
        pass
    _PDF_FONT_NAME = "Helvetica"
    return _PDF_FONT_NAME


@dataclass
class ViewProjection:
    name: str
    visible: Any
    hidden: Any


def _context_caption(context: dict[str, Any] | None) -> str:
    if not context:
        return ""
    ordered = ("line_id", "service", "nominal_size", "pressure_class", "material")
    return " · ".join(
        f"{key.replace('_', ' ')}: {context[key]}"
        for key in ordered
        if key in context and context[key] not in (None, "")
    )


def _make_views(shape: Any) -> list[ViewProjection]:
    from build123d import Drawing

    view_specs = [
        ("front", (0, -1, 0), (0, 0, 1)),
        ("top", (0, 0, 1), (0, 1, 0)),
        ("left", (-1, 0, 0), (0, 0, 1)),
    ]
    views: list[ViewProjection] = []
    for name, look_from, look_up in view_specs:
        drawing = Drawing(shape, look_from=look_from, look_up=look_up, with_hidden=True)
        views.append(ViewProjection(name, drawing.visible_lines, drawing.hidden_lines))
    return views


def _measure_shape(shape: Any) -> dict[str, float | int]:
    bbox = shape.bounding_box()
    od = max(float(bbox.size.X), float(bbox.size.Y))
    thickness = float(bbox.size.Z)
    cylinders = [
        face
        for face in shape.faces()
        if str(getattr(face, "geom_type", "")).upper().endswith("CYLINDER")
    ]
    outer = max(cylinders, key=lambda face: float(face.radius))
    outer_radius = float(outer.radius)
    centered = [
        face
        for face in cylinders
        if abs(float(face.axis_of_rotation.position.X)) <= 1e-6
        and abs(float(face.axis_of_rotation.position.Y)) <= 1e-6
        and float(face.radius) < outer_radius - 1e-6
    ]
    center_hole_face = max(centered, key=lambda face: float(face.radius))
    bolt_faces = [
        face for face in cylinders if face is not outer and face is not center_hole_face
    ]
    bolt_diameter = 2 * sum(float(face.radius) for face in bolt_faces) / len(bolt_faces)
    pcd = 2 * sum(
        hypot(
            float(face.axis_of_rotation.position.X),
            float(face.axis_of_rotation.position.Y),
        )
        for face in bolt_faces
    ) / len(bolt_faces)
    return {
        "od": od,
        "thickness": thickness,
        "center_hole": 2 * float(center_hole_face.radius),
        "bolt_count": len(bolt_faces),
        "bolt_diameter": bolt_diameter,
        "pcd": pcd,
    }


def _edge_points(edge: Any) -> list[tuple[float, float]]:
    return [(float(p.X), float(p.Y)) for p in edge.positions(deflection=0.35)]


def _view_bounds(view: ViewProjection) -> tuple[float, float, float, float]:
    points: list[tuple[float, float]] = []
    for compound in (view.visible, view.hidden):
        for edge in compound.edges():
            points.extend(_edge_points(edge))
    if not points:
        return (-1.0, -1.0, 1.0, 1.0)
    xs = [p[0] for p in points]
    ys = [p[1] for p in points]
    return min(xs), min(ys), max(xs), max(ys)


def _transformer(
    view: ViewProjection,
    left: float,
    bottom: float,
    width: float,
    height: float,
    y_down: bool = False,
):
    min_x, min_y, max_x, max_y = _view_bounds(view)
    span_x = max(max_x - min_x, 1e-6)
    span_y = max(max_y - min_y, 1e-6)
    scale = min((width - 24) / span_x, (height - 24) / span_y)
    mid_x = (min_x + max_x) / 2
    mid_y = (min_y + max_y) / 2

    def transform(point: tuple[float, float]) -> tuple[float, float]:
        y = (
            bottom + height / 2 - (point[1] - mid_y) * scale
            if y_down
            else bottom + height / 2 + (point[1] - mid_y) * scale
        )
        return (
            left + width / 2 + (point[0] - mid_x) * scale,
            y,
        )

    return transform


