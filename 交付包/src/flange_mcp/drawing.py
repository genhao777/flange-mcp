def _arrowhead(pdf: Any, x: float, y: float, dx: float, dy: float, size: float = 4.0) -> None:
    length = sqrt(dx * dx + dy * dy) or 1.0
    ux, uy = dx / length, dy / length
    px, py = -uy, ux
    back_x, back_y = x - ux * size, y - uy * size
    path = pdf.beginPath()
    path.moveTo(x, y)
    path.lineTo(back_x + px * size * 0.55, back_y + py * size * 0.55)
    path.lineTo(back_x - px * size * 0.55, back_y - py * size * 0.55)
    path.close()
    pdf.drawPath(path, fill=1, stroke=0)


